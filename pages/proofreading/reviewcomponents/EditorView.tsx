/**
 * pages/proofreading/reviewcomponents/EditorView.tsx
 * 
 * A specialized editor component that alternates between a standard Markdown text area
 * and an interactive line-by-line Diff View.
 * Responsibilities include:
 * - Rendering raw markdown for editing.
 * - Rendering color-coded diff lines (additions/removals).
 * - Providing per-line "Accept" or "Discard" buttons for AI suggestions.
 */

import React from 'react';
import { FileText, Sparkles, Check, X } from 'lucide-react';

interface EditorViewProps {
  /** Mode toggle state */
  isDiffMode: boolean;
  /** Current text state and setter for manual editing */
  text: string;
  setText: (val: string) => void;
  /** Diff tokens generated by 'diff' library */
  diffParts: any[];
  /** The target corrected markdown suggestion from AI */
  suggestion: string | null;
  /** Logic flag to show/hide suggestion toggles */
  hasPendingChanges: boolean;
  setIsDiffMode: (val: boolean) => void;
  /** Granular line callbacks */
  onAcceptChange: (index: number) => void;
  onDiscardChange: (index: number) => void;
}

export const EditorView: React.FC<EditorViewProps> = ({
  isDiffMode,
  text,
  setText,
  diffParts,
  suggestion,
  hasPendingChanges,
  setIsDiffMode,
  onAcceptChange,
  onDiscardChange
}) => {
  return (
    <div className="flex-1 flex flex-col min-h-0 relative bg-card border border-border rounded-xl shadow-sm overflow-hidden">
       {/* Editor Panel Header */}
       <div className="flex items-center justify-between px-4 py-2 bg-muted border-b border-border">
          <label className="text-xs font-bold text-muted-foreground uppercase tracking-wider flex items-center gap-1.5">
            <FileText size={14} /> {isDiffMode ? 'Interactive Diff' : 'Editor'}
          </label>
          
          {/* Prompt to switch into Diff Mode if AI suggestions are waiting */}
          {suggestion && !isDiffMode && hasPendingChanges && (
            <button onClick={() => setIsDiffMode(true)} className="text-xs text-blue-600 font-semibold hover:underline flex items-center gap-1">
              <Sparkles size={12} /> View Suggestions
            </button>
          )}
       </div>
        
        <div className="relative flex-1 overflow-auto bg-white">
           {isDiffMode ? (
             /* DIFF MODE VIEW */
             <div className="font-mono text-sm leading-relaxed min-w-full">
               {diffParts.map((part, i) => {
                 const bgColor = part.added ? 'bg-green-50' : part.removed ? 'bg-red-50' : 'bg-transparent';
                 const textColor = part.added ? 'text-green-800' : part.removed ? 'text-red-800' : 'text-slate-700';
                 const prefix = part.added ? '+' : part.removed ? '-' : ' ';
                 const isChange = part.added || part.removed;

                 return (
                   <div key={i} className={`relative group/line ${bgColor} ${textColor} flex`}>
                     {/* Gutter / Sign Column */}
                     <div className="w-10 flex-shrink-0 text-right pr-3 select-none text-muted-foreground/50 border-r border-border bg-muted/30 py-0.5">
                       {prefix}
                     </div>
                     {/* Line Content */}
                     <pre className="flex-1 px-4 py-0.5 whitespace-pre-wrap">{part.value}</pre>
                     
                     {/* Hover Actions per line */}
                     {isChange && (
                       <div className="absolute right-4 top-1/2 -translate-y-1/2 flex items-center gap-1 opacity-0 group-hover/line:opacity-100 transition-opacity">
                         <button 
                           title="Accept"
                           onClick={() => onAcceptChange(i)}
                           className="p-1 bg-white border border-green-200 text-green-600 rounded shadow hover:bg-green-50"
                         >
                           <Check size={14} />
                         </button>
                         <button 
                           title="Reject"
                           onClick={() => onDiscardChange(i)}
                           className="p-1 bg-white border border-red-200 text-red-600 rounded shadow hover:bg-red-50"
                         >
                           <X size={14} />
                         </button>
                       </div>
                     )}
                   </div>
                 );
               })}
             </div>
           ) : (
             /* STANDARD EDITOR VIEW */
             <textarea 
              className="w-full h-full p-4 font-mono text-sm resize-none focus:ring-0 outline-none leading-relaxed bg-white"
              value={text}
              onChange={(e) => setText(e.target.value)}
              placeholder="Extracted text..."
            />
           )}
        </div>
    </div>
  );
};